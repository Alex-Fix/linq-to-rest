using System.Collections;
using System.Diagnostics.CodeAnalysis;
using System.Linq.Expressions;
using LinqToRest.Client.Translation;
using LinqToRest.Modeling;

namespace LinqToRest.Client;

/// <summary>
/// A set of DTOs exposed by the API: query it with LINQ and the async operators, and add, attach, update or remove
/// DTOs to save with <see cref="RestDataContext.SaveChangesAsync"/>.
/// </summary>
/// <typeparam name="TDto">The DTO type.</typeparam>
[SuppressMessage("Naming", "CA1710:Identifiers should have correct suffix", Justification = "Named like EF Core's DbSet; it's a queryable set, not a collection.")]
public sealed class DtoSet<TDto> : IOrderedQueryable<TDto>, IDtoSet
    where TDto : class, IDto
{
    private readonly RestDataContext _context;

    internal DtoSet(RestDataContext context, DtoType type, RestQueryProvider provider)
    {
        _context = context;
        Type = type;
        Provider = provider;
        Expression = Expression.Constant(this);
    }

    /// <inheritdoc />
    public Type ElementType => typeof(TDto);

    /// <inheritdoc />
    public Expression Expression { get; }

    /// <inheritdoc />
    public IQueryProvider Provider { get; }

    DtoType IDtoSet.Type => Type;

    internal DtoType Type { get; }

    /// <summary>Starts tracking a new DTO, inserted on save. Its key is generated by the server.</summary>
    /// <param name="dto">The DTO.</param>
    public void Add(TDto dto)
    {
        ArgumentNullException.ThrowIfNull(dto);
        _context.Tracker.Add(dto, Type);
    }

    /// <summary>Starts tracking an existing DTO as unchanged; later changes to it are saved.</summary>
    /// <param name="dto">The DTO, with its key and concurrency token.</param>
    public void Attach(TDto dto)
    {
        ArgumentNullException.ThrowIfNull(dto);
        _context.Tracker.Attach(dto, Type);
    }

    /// <summary>Tracks an existing DTO with every writable member marked modified.</summary>
    /// <param name="dto">The DTO, with its key and concurrency token.</param>
    public void Update(TDto dto)
    {
        ArgumentNullException.ThrowIfNull(dto);
        _context.Tracker.Update(dto, Type);
    }

    /// <summary>Marks a DTO deleted on save (an added one is simply forgotten).</summary>
    /// <param name="dto">The DTO, with its key and concurrency token.</param>
    public void Remove(TDto dto)
    {
        ArgumentNullException.ThrowIfNull(dto);
        _context.Tracker.Remove(dto, Type);
    }

    /// <summary>Not supported: LinqToRest never blocks on HTTP. Use the async operators such as <c>ToListAsync</c>.</summary>
    /// <returns>Never returns.</returns>
    public IEnumerator<TDto> GetEnumerator() => throw RestQueryProvider.Synchronous();

    IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();
}
