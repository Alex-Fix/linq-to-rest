using System.Collections;
using System.Diagnostics.CodeAnalysis;
using System.Linq.Expressions;
using LinqToRest.Client.Translation;

namespace LinqToRest.Client;

/// <summary>
/// A set of entities exposed by the API: query it with LINQ and the async operators, and add, attach, update or remove
/// entities to save with <see cref="RestDataContext.SaveChangesAsync"/>.
/// </summary>
/// <typeparam name="TEntity">The entity type.</typeparam>
[SuppressMessage("Naming", "CA1710:Identifiers should have correct suffix", Justification = "Named like EF Core's DbSet; it's a queryable set, not a collection.")]
public sealed class RestSet<TEntity> : IOrderedQueryable<TEntity>, IRestSet
    where TEntity : class
{
    private readonly RestDataContext _context;

    internal RestSet(RestDataContext context, ClientSet type, RestQueryProvider provider)
    {
        _context = context;
        Type = type;
        Provider = provider;
        Expression = Expression.Constant(this);
    }

    /// <inheritdoc />
    public Type ElementType => typeof(TEntity);

    /// <inheritdoc />
    public Expression Expression { get; }

    /// <inheritdoc />
    public IQueryProvider Provider { get; }

    ClientSet IRestSet.Type => Type;

    internal ClientSet Type { get; }

    /// <summary>Starts tracking a new entity, inserted on save. Its key is generated by the server.</summary>
    /// <param name="entity">The entity.</param>
    public void Add(TEntity entity)
    {
        ArgumentNullException.ThrowIfNull(entity);
        _context.Tracker.Add(entity, Type);
    }

    /// <summary>Starts tracking an existing entity as unchanged; later changes to it are saved.</summary>
    /// <param name="entity">The entity, with its key and concurrency token.</param>
    public void Attach(TEntity entity)
    {
        ArgumentNullException.ThrowIfNull(entity);
        _context.Tracker.Attach(entity, Type);
    }

    /// <summary>Tracks an existing entity with every writable member marked modified.</summary>
    /// <param name="entity">The entity, with its key and concurrency token.</param>
    public void Update(TEntity entity)
    {
        ArgumentNullException.ThrowIfNull(entity);
        _context.Tracker.Update(entity, Type);
    }

    /// <summary>Marks an entity deleted on save (an added one is simply forgotten).</summary>
    /// <param name="entity">The entity, with its key and concurrency token.</param>
    public void Remove(TEntity entity)
    {
        ArgumentNullException.ThrowIfNull(entity);
        _context.Tracker.Remove(entity, Type);
    }

    /// <summary>Not supported: LinqToRest never blocks on HTTP. Use the async operators such as <c>ToListAsync</c>.</summary>
    /// <returns>Never returns.</returns>
    public IEnumerator<TEntity> GetEnumerator() => throw RestQueryProvider.Synchronous();

    IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();
}
