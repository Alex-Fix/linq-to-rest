using System.Globalization;
using System.Text;
using System.Text.Json;
using RestToLinq.Modeling;

namespace RestToLinq.TypeScript;

/// <summary>Writes the TypeScript DTO types, proxy types, runtime model and context factory for a DTO model.</summary>
internal sealed class TypeScriptEmitter(DtoModel model, string name, string importModule, string source)
{
    private readonly List<string> _warnings = [];
    private readonly SortedSet<string> _imports = new(StringComparer.Ordinal) { "Context", "ContextOptions", "DtoSet", "EntityProxy", "Model" };

    public IReadOnlyList<string> Warnings => _warnings;

    public string Emit()
    {
        var types = model.Types.OrderBy(type => type.ClrType.Name, StringComparer.Ordinal).ToList();
        var duplicate = types.GroupBy(type => type.ClrType.Name).FirstOrDefault(group => group.Count() > 1);
        if (duplicate is not null)
        {
            throw new GeneratorException($"Two DTOs are named {duplicate.Key} ({string.Join(", ", duplicate.Select(type => type.ClrType.FullName))}); TypeScript needs unique names.");
        }

        var body = new StringBuilder();
        foreach (var enumType in Enums(types))
        {
            body.Append(CultureInfo.InvariantCulture, $"export type {enumType.Name} = {EnumUnion(enumType)};\n\n");
        }

        foreach (var type in types)
        {
            WriteDto(body, type);
        }

        foreach (var type in types)
        {
            WriteProxy(body, type);
        }

        WriteModel(body, types);
        WriteContext(body, types);

        var header = new StringBuilder();
        header.Append("// <auto-generated>\n");
        header.Append(CultureInfo.InvariantCulture, $"// Generated by resttolinq-ts from {source}. Do not edit; run the generator again instead.\n");
        header.Append("// </auto-generated>\n");
        header.Append("import {\n  createContext,\n");
        foreach (var import in _imports)
        {
            header.Append(CultureInfo.InvariantCulture, $"  type {import},\n");
        }

        header.Append(CultureInfo.InvariantCulture, $"}} from \"{importModule}\";\n\n");
        return header.Append(body).ToString().TrimEnd('\n') + "\n";
    }

    private static List<Type> Enums(IEnumerable<DtoType> types)
    {
        var enums = types.SelectMany(type => type.Properties)
            .Select(property => Nullable.GetUnderlyingType(property.ElementType ?? property.ClrType) ?? property.ElementType ?? property.ClrType)
            .Where(type => type.IsEnum)
            .Distinct()
            .OrderBy(type => type.Name, StringComparer.Ordinal)
            .ToList();
        var duplicate = enums.GroupBy(type => type.Name).FirstOrDefault(group => group.Count() > 1);
        return duplicate is null
            ? enums
            : throw new GeneratorException($"Two enums are named {duplicate.Key}; TypeScript needs unique names.");
    }

    private static string EnumUnion(Type enumType) =>
        enumType.IsDefined(typeof(FlagsAttribute), inherit: false)
            ? "string" // Flag combinations ("Read, Write") have no closed list.
            : string.Join(" | ", Enum.GetNames(enumType).Select(Quote));

    private void WriteDto(StringBuilder body, DtoType type)
    {
        body.Append(CultureInfo.InvariantCulture, $"export interface {type.ClrType.Name} {{\n");
        foreach (var property in type.Properties)
        {
            var element = Nullable.GetUnderlyingType(property.ElementType ?? property.ClrType) ?? property.ElementType ?? property.ClrType;
            if (element == typeof(decimal) || element == typeof(long))
            {
                var note = element == typeof(decimal) ? "decimal: JavaScript numbers keep about 15 significant digits." : "long: JavaScript numbers are exact only up to 2^53.";
                body.Append(CultureInfo.InvariantCulture, $"  /** {note} */\n");
                _warnings.Add($"{type}.{property.Name} is {(element == typeof(decimal) ? "decimal" : "long")}: {note[(note.IndexOf(':', StringComparison.Ordinal) + 2)..]}");
            }

            var value = ValueType(element) + (property.IsCollection ? "[]" : property.IsNullable ? " | null" : "");
            body.Append(CultureInfo.InvariantCulture, $"  {(property.IsWritable ? "" : "readonly ")}{property.WireName}: {value};\n");
        }

        foreach (var navigation in type.Navigations)
        {
            var target = navigation.Target.ClrType.Name;
            body.Append(CultureInfo.InvariantCulture, $"  {navigation.WireName}: {(navigation.IsCollection ? $"{target}[]" : $"{target} | null")};\n");
        }

        body.Append("}\n\n");
    }

    private void WriteProxy(StringBuilder body, DtoType type)
    {
        body.Append(CultureInfo.InvariantCulture, $"export interface {ProxyName(type)} extends EntityProxy<{type.ClrType.Name}> {{\n");
        foreach (var property in type.Properties)
        {
            var element = Nullable.GetUnderlyingType(property.ElementType ?? property.ClrType) ?? property.ElementType ?? property.ClrType;
            string expression;
            if (property.IsCollection)
            {
                _imports.Add("PrimitiveCollectionExpr");
                expression = $"PrimitiveCollectionExpr<{ExpressionType(element, nullable: false)}>";
            }
            else
            {
                expression = ExpressionType(element, property.IsNullable);
            }

            if (property.IsSortable)
            {
                _imports.Add("Sortable");
                expression += " & Sortable";
            }

            body.Append(CultureInfo.InvariantCulture, $"  readonly {property.WireName}: {expression};\n");
        }

        foreach (var navigation in type.Navigations)
        {
            if (navigation.IsCollection)
            {
                _imports.Add("CollectionExpr");
            }

            var proxy = ProxyName(navigation.Target);
            body.Append(CultureInfo.InvariantCulture, $"  readonly {navigation.WireName}: {(navigation.IsCollection ? $"CollectionExpr<{proxy}>" : proxy)};\n");
        }

        body.Append("}\n\n");
    }

    private void WriteModel(StringBuilder body, IEnumerable<DtoType> types)
    {
        body.Append(CultureInfo.InvariantCulture, $"export const {ModelName} = {{\n  sets: {{\n");
        foreach (var type in types.OrderBy(type => type.SetName, StringComparer.Ordinal))
        {
            body.Append(CultureInfo.InvariantCulture, $"    {type.SetName}: {{\n");
            body.Append(CultureInfo.InvariantCulture, $"      name: {Quote(type.SetName)},\n");
            body.Append(CultureInfo.InvariantCulture, $"      key: [{string.Join(", ", type.Key.Select(key => Quote(key.WireName)))}],\n");
            body.Append(CultureInfo.InvariantCulture, $"      token: {(type.ConcurrencyToken is null ? "null" : Quote(type.ConcurrencyToken.WireName))},\n");
            body.Append("      members: [\n");
            foreach (var property in type.Properties)
            {
                var element = Nullable.GetUnderlyingType(property.ElementType ?? property.ClrType) ?? property.ElementType ?? property.ClrType;
                body.Append(CultureInfo.InvariantCulture,
                    $"        {{ name: {Quote(property.WireName)}, kind: {Quote(Kind(element))}, nullable: {Bool(property.IsNullable)}, collection: {Bool(property.IsCollection)}, filterable: {Bool(property.IsFilterable)}, sortable: {Bool(property.IsSortable)}, writable: {Bool(property.IsWritable)} }},\n");
            }

            body.Append("      ],\n");
            if (type.Navigations.Count == 0)
            {
                body.Append("      navigations: [],\n");
            }
            else
            {
                body.Append("      navigations: [\n");
                foreach (var navigation in type.Navigations)
                {
                    body.Append(CultureInfo.InvariantCulture,
                        $"        {{ name: {Quote(navigation.WireName)}, target: {Quote(navigation.Target.SetName)}, collection: {Bool(navigation.IsCollection)}, foreignKey: {(navigation.ForeignKey is null ? "null" : Quote(navigation.ForeignKey.WireName))} }},\n");
                }

                body.Append("      ],\n");
            }

            var pagination = type.Pagination;
            var modes = new List<string>();
            if (pagination.Modes.HasFlag(PaginationModes.Offset))
            {
                modes.Add(Quote("offset"));
            }

            if (pagination.Modes.HasFlag(PaginationModes.Cursor))
            {
                modes.Add(Quote("cursor"));
            }

            body.Append(CultureInfo.InvariantCulture, $"      pagination: {{ modes: [{string.Join(", ", modes)}], defaultPageSize: {pagination.DefaultPageSize}, maxPageSize: {pagination.MaxPageSize} }},\n");
            body.Append("    },\n");
        }

        body.Append("  },\n} as const satisfies Model;\n\n");
    }

    private void WriteContext(StringBuilder body, IEnumerable<DtoType> types)
    {
        body.Append(CultureInfo.InvariantCulture, $"export interface {name}Context extends Context {{\n");
        foreach (var type in types.OrderBy(type => type.SetName, StringComparer.Ordinal))
        {
            body.Append(CultureInfo.InvariantCulture, $"  readonly {type.SetName}: DtoSet<{type.ClrType.Name}, {ProxyName(type)}>;\n");
        }

        body.Append("}\n\n");
        body.Append(CultureInfo.InvariantCulture, $"export function create{name}(options: ContextOptions): {name}Context {{\n");
        body.Append(CultureInfo.InvariantCulture, $"  return createContext({ModelName}, options) as unknown as {name}Context;\n");
        body.Append("}\n");
    }

    private string ModelName => JsonNamingPolicy.CamelCase.ConvertName(name) + "Model";

    private static string ProxyName(DtoType type) =>
        (type.ClrType.Name.EndsWith("Dto", StringComparison.Ordinal) ? type.ClrType.Name[..^3] : type.ClrType.Name) + "Proxy";

    private static string ValueType(Type type) =>
        type == typeof(bool) ? "boolean"
        : ScalarTypes.IsNumeric(type) ? "number"
        : type.IsEnum ? type.Name
        : "string";

    private string ExpressionType(Type type, bool nullable)
    {
        string Generic(string expression, string value)
        {
            _imports.Add(expression);
            return nullable ? $"{expression}<{value} | null>" : expression;
        }

        string Typed(string expression, string value)
        {
            _imports.Add(expression);
            return $"{expression}<{value}{(nullable ? " | null" : "")}>";
        }

        return Kind(type) switch
        {
            "number" => Generic("NumberExpr", "number"),
            "string" => Generic("StringExpr", "string"),
            "boolean" => nullable ? Typed("Expr", "boolean") : Generic("BoolExpr", "boolean"),
            "enum" => Typed("OrderedExpr", type.Name),
            "datetime" or "datetimeoffset" => Generic("DateTimeExpr", "string"),
            "dateonly" => Generic("DateOnlyExpr", "string"),
            "timeonly" => Generic("TimeOnlyExpr", "string"),
            "timespan" => Typed("OrderedExpr", "string"),
            _ => Typed("Expr", "string"),
        };
    }

    private static string Kind(Type type) =>
        type == typeof(bool) ? "boolean"
        : ScalarTypes.IsNumeric(type) ? "number"
        : type == typeof(string) ? "string"
        : type.IsEnum ? "enum"
        : type == typeof(Guid) ? "guid"
        : type == typeof(DateTime) ? "datetime"
        : type == typeof(DateTimeOffset) ? "datetimeoffset"
        : type == typeof(DateOnly) ? "dateonly"
        : type == typeof(TimeOnly) ? "timeonly"
        : type == typeof(TimeSpan) ? "timespan"
        : "binary";

    private static string Bool(bool value) => value ? "true" : "false";

    private static string Quote(string value) => JsonSerializer.Serialize(value);
}
