using System.Globalization;
using System.Text;
using LinqToRest.Modeling;

namespace LinqToRest.CodeGen;

/// <summary>
/// Writes the C# client for a model document: an enum per enum, a <c>partial</c> class per set, the context with a
/// <c>RestSet</c> per set and its bound <c>ClientModel</c>, and an <c>Add{Context}</c> registration extension.
/// </summary>
internal sealed class CSharpEmitter(RestModel model, string ns, string context, string source)
{
    // Lowercase C# keywords; enum members may be lowercase, everything else is PascalCase.
    private static readonly HashSet<string> Keywords =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    ];

    // Members a RestDataContext (and object) already has, which a set property can't reuse.
    private static readonly HashSet<string> ContextMembers =
    [
        "Model", "Set", "Entry", "SaveChangesAsync", "Equals", "GetHashCode", "GetType", "ToString", "MemberwiseClone",
    ];

    public string Emit()
    {
        var body = new StringBuilder();
        body.Append("// <auto-generated>\n");
        body.Append(CultureInfo.InvariantCulture, $"// Generated by linqtorest-gen from {source}. Do not edit; run the generator again instead.\n");
        body.Append("// </auto-generated>\n");
        body.Append("#nullable enable\n\n");
        body.Append("using System;\nusing System.Collections.Generic;\nusing System.Net.Http;\nusing LinqToRest.Client;\nusing LinqToRest.Modeling;\nusing Microsoft.Extensions.DependencyInjection;\n\n");
        body.Append(CultureInfo.InvariantCulture, $"namespace {ns};\n");

        foreach (var enumModel in model.Enums.OrderBy(enumModel => enumModel.Name, StringComparer.Ordinal))
        {
            body.Append(CultureInfo.InvariantCulture, $"\npublic enum {enumModel.Name}\n{{\n");
            foreach (var member in enumModel.Members)
            {
                body.Append(CultureInfo.InvariantCulture, $"    {Identifier(member)},\n");
            }

            body.Append("}\n");
        }

        foreach (var set in model.Sets.OrderBy(set => set.TypeName, StringComparer.Ordinal))
        {
            WriteClass(body, set);
        }

        WriteContext(body);
        return body.ToString();
    }

    private void WriteClass(StringBuilder body, RestSetModel set)
    {
        body.Append(CultureInfo.InvariantCulture, $"\npublic sealed partial class {set.TypeName}\n{{\n");
        foreach (var property in set.Properties)
        {
            var type = ClrType(property.Type);
            var name = Member(set, property.Name);
            if (property.IsCollection)
            {
                body.Append(CultureInfo.InvariantCulture, $"    public List<{type}> {name} {{ get; set; }} = [];\n");
            }
            else if (property.IsNullable)
            {
                body.Append(CultureInfo.InvariantCulture, $"    public {type}? {name} {{ get; set; }}\n");
            }
            else
            {
                var initializer = type switch
                {
                    "string" => " = \"\";",
                    "byte[]" => " = [];",
                    _ => "",
                };
                body.Append(CultureInfo.InvariantCulture, $"    public {type} {name} {{ get; set; }}{initializer}\n");
            }
        }

        foreach (var navigation in set.Navigations)
        {
            var target = model.FindSet(navigation.Target)!.TypeName;
            var name = Member(set, navigation.Name);
            if (navigation.IsCollection)
            {
                body.Append(CultureInfo.InvariantCulture, $"    public List<{target}> {name} {{ get; set; }} = [];\n");
            }
            else
            {
                body.Append(CultureInfo.InvariantCulture, $"    public {target}? {name} {{ get; set; }}\n");
            }
        }

        body.Append("}\n");
    }

    private void WriteContext(StringBuilder body)
    {
        var sets = model.Sets.OrderBy(set => set.Name, StringComparer.Ordinal).ToList();
        body.Append(CultureInfo.InvariantCulture, $"\npublic sealed partial class {context}(RestDataContextOptions<{context}> options) : RestDataContext(options)\n{{\n");
        body.Append("    /// <summary>Gets the model document bound to the generated classes.</summary>\n");
        body.Append("    public static ClientModel Model { get; } = ClientModel.Bind(\n");
        body.Append(CultureInfo.InvariantCulture, $"        RestModel.Parse(\"\"\"{model.ToJson(indented: false)}\"\"\"),\n");
        body.Append("        new Dictionary<string, Type>\n        {\n");
        foreach (var set in sets)
        {
            body.Append(CultureInfo.InvariantCulture, $"            [\"{set.Name}\"] = typeof({set.TypeName}),\n");
        }

        body.Append("        });\n");
        foreach (var set in sets)
        {
            var property = Pascal(set.Name);
            if (ContextMembers.Contains(property) || property == context)
            {
                throw new GeneratorException($"The set '{set.Name}' would be the property {context}.{property}, which the context already has. Rename the set.");
            }

            body.Append(CultureInfo.InvariantCulture, $"\n    public RestSet<{set.TypeName}> {property} => Set<{set.TypeName}>();\n");
        }

        body.Append("}\n");
        body.Append(CultureInfo.InvariantCulture, $"\npublic static class {context}ServiceCollectionExtensions\n{{\n");
        body.Append(CultureInfo.InvariantCulture, $"    /// <summary>Registers <see cref=\"{context}\"/> as a scoped service with its own named <see cref=\"HttpClient\"/>.</summary>\n");
        body.Append("    /// <param name=\"services\">The service collection.</param>\n");
        body.Append("    /// <param name=\"configureClient\">Configures the client; set its base address to the API root, ending with <c>/</c>.</param>\n");
        body.Append("    /// <returns>The HTTP client builder.</returns>\n");
        body.Append(CultureInfo.InvariantCulture, $"    public static IHttpClientBuilder Add{context}(this IServiceCollection services, Action<HttpClient> configureClient) =>\n");
        body.Append(CultureInfo.InvariantCulture, $"        services.AddRestDataContext<{context}>({context}.Model, configureClient);\n");
        body.Append("}\n");
    }

    private static string Member(RestSetModel set, string wireName)
    {
        var name = Pascal(wireName);
        return name == set.TypeName
            ? throw new GeneratorException($"The member '{set.Name}.{wireName}' would be named like its class {set.TypeName}, which C# doesn't allow. Rename one of them.")
            : name;
    }

    private string ClrType(string type) => type switch
    {
        "bool" => "bool",
        "uint8" => "byte",
        "int16" => "short",
        "int32" => "int",
        "int64" => "long",
        "float32" => "float",
        "float64" => "double",
        "decimal" => "decimal",
        "string" => "string",
        "guid" => "Guid",
        "dateTime" => "DateTime",
        "dateTimeOffset" => "DateTimeOffset",
        "dateOnly" => "DateOnly",
        "timeOnly" => "TimeOnly",
        "timeSpan" => "TimeSpan",
        "bytes" => "byte[]",
        _ when model.FindEnum(type) is not null => type,
        _ => throw new GeneratorException($"The model type '{type}' has no C# equivalent."),
    };

    private static string Pascal(string wireName) => char.ToUpperInvariant(wireName[0]) + wireName[1..];

    private static string Identifier(string name) => Keywords.Contains(name) ? "@" + name : name;
}
