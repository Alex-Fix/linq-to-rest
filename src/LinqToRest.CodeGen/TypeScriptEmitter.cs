using System.Globalization;
using System.Text;
using System.Text.Json;
using LinqToRest.Modeling;
using LinqToRest.Protocol;

namespace LinqToRest.CodeGen;

/// <summary>Writes the TypeScript row types, proxy types, runtime model and context factory for a model document.</summary>
internal sealed class TypeScriptEmitter(RestModel model, string name, string importModule, string source)
{
    private readonly List<string> _warnings = [];
    private readonly SortedSet<string> _imports = new(StringComparer.Ordinal) { "Context", "ContextOptions", "EntityProxy", "Model", "RestSet" };

    public IReadOnlyList<string> Warnings => _warnings;

    public string Emit()
    {
        var sets = model.Sets.OrderBy(set => set.TypeName, StringComparer.Ordinal).ToList();
        var body = new StringBuilder();
        foreach (var enumModel in model.Enums.OrderBy(enumModel => enumModel.Name, StringComparer.Ordinal))
        {
            body.Append(CultureInfo.InvariantCulture, $"export type {enumModel.Name} = {string.Join(" | ", enumModel.Members.Select(Quote))};\n\n");
        }

        foreach (var set in sets)
        {
            WriteRow(body, set);
        }

        foreach (var set in sets)
        {
            WriteProxy(body, set);
        }

        WriteModel(body);
        WriteContext(body);

        var header = new StringBuilder();
        header.Append("// <auto-generated>\n");
        header.Append(CultureInfo.InvariantCulture, $"// Generated by linqtorest-gen from {source}. Do not edit; run the generator again instead.\n");
        header.Append("// </auto-generated>\n");
        header.Append("import {\n  createContext,\n");
        foreach (var import in _imports)
        {
            header.Append(CultureInfo.InvariantCulture, $"  type {import},\n");
        }

        header.Append(CultureInfo.InvariantCulture, $"}} from \"{importModule}\";\n\n");
        return header.Append(body).ToString().TrimEnd('\n') + "\n";
    }

    private void WriteRow(StringBuilder body, RestSetModel set)
    {
        body.Append(CultureInfo.InvariantCulture, $"export interface {set.TypeName} {{\n");
        foreach (var property in set.Properties)
        {
            if (property.Type is "decimal" or "int64")
            {
                var note = property.Type == "decimal" ? "decimal: JavaScript numbers keep about 15 significant digits." : "long: JavaScript numbers are exact only up to 2^53.";
                body.Append(CultureInfo.InvariantCulture, $"  /** {note} */\n");
                _warnings.Add($"{set.TypeName}.{property.Name} is {(property.Type == "decimal" ? "decimal" : "long")}: {note[(note.IndexOf(':', StringComparison.Ordinal) + 2)..]}");
            }

            var value = ValueType(property.Type) + (property.IsCollection ? "[]" : property.IsNullable ? " | null" : "");
            body.Append(CultureInfo.InvariantCulture, $"  {(property.IsWritable ? "" : "readonly ")}{property.Name}: {value};\n");
        }

        foreach (var navigation in set.Navigations)
        {
            var target = Target(navigation).TypeName;
            body.Append(CultureInfo.InvariantCulture, $"  {navigation.Name}: {(navigation.IsCollection ? $"{target}[]" : $"{target} | null")};\n");
        }

        body.Append("}\n\n");
    }

    private void WriteProxy(StringBuilder body, RestSetModel set)
    {
        body.Append(CultureInfo.InvariantCulture, $"export interface {ProxyName(set)} extends EntityProxy<{set.TypeName}> {{\n");
        foreach (var property in set.Properties)
        {
            string expression;
            if (property.IsCollection)
            {
                _imports.Add("PrimitiveCollectionExpr");
                expression = $"PrimitiveCollectionExpr<{ExpressionType(property.Type, nullable: false)}>";
            }
            else
            {
                expression = ExpressionType(property.Type, property.IsNullable);
            }

            if (property.IsSortable)
            {
                _imports.Add("Sortable");
                expression += " & Sortable";
            }

            body.Append(CultureInfo.InvariantCulture, $"  readonly {property.Name}: {expression};\n");
        }

        foreach (var navigation in set.Navigations)
        {
            if (navigation.IsCollection)
            {
                _imports.Add("CollectionExpr");
            }

            var proxy = ProxyName(Target(navigation));
            body.Append(CultureInfo.InvariantCulture, $"  readonly {navigation.Name}: {(navigation.IsCollection ? $"CollectionExpr<{proxy}>" : proxy)};\n");
        }

        body.Append("}\n\n");
    }

    private void WriteModel(StringBuilder body)
    {
        body.Append(CultureInfo.InvariantCulture, $"export const {ModelName} = {{\n  sets: {{\n");
        foreach (var set in model.Sets.OrderBy(set => set.Name, StringComparer.Ordinal))
        {
            body.Append(CultureInfo.InvariantCulture, $"    {set.Name}: {{\n");
            body.Append(CultureInfo.InvariantCulture, $"      name: {Quote(set.Name)},\n");
            body.Append(CultureInfo.InvariantCulture, $"      key: [{string.Join(", ", set.Key.Select(Quote))}],\n");
            body.Append(CultureInfo.InvariantCulture, $"      token: {(set.ConcurrencyToken is null ? "null" : Quote(set.ConcurrencyToken))},\n");
            body.Append(CultureInfo.InvariantCulture, $"      writes: [{string.Join(", ", Writes(set).Select(Quote))}],\n");
            body.Append("      members: [\n");
            foreach (var property in set.Properties)
            {
                body.Append(CultureInfo.InvariantCulture,
                    $"        {{ name: {Quote(property.Name)}, kind: {Quote(Kind(property.Type))}, nullable: {Bool(property.IsNullable)}, collection: {Bool(property.IsCollection)}, filterable: {Bool(property.IsFilterable)}, sortable: {Bool(property.IsSortable)}, writable: {Bool(property.IsWritable)}{Rules(property.Rules)} }},\n");
            }

            body.Append("      ],\n");
            if (set.Navigations.Count == 0)
            {
                body.Append("      navigations: [],\n");
            }
            else
            {
                body.Append("      navigations: [\n");
                foreach (var navigation in set.Navigations)
                {
                    body.Append(CultureInfo.InvariantCulture,
                        $"        {{ name: {Quote(navigation.Name)}, target: {Quote(navigation.Target)}, collection: {Bool(navigation.IsCollection)}, foreignKey: {(navigation.ForeignKey is [var foreignKey] ? Quote(foreignKey) : "null")} }},\n");
                }

                body.Append("      ],\n");
            }

            var pagination = set.Pagination;
            var modes = new List<string>();
            if (pagination.Modes.HasFlag(PaginationModes.Offset))
            {
                modes.Add(Quote("offset"));
            }

            if (pagination.Modes.HasFlag(PaginationModes.Cursor))
            {
                modes.Add(Quote("cursor"));
            }

            body.Append(CultureInfo.InvariantCulture, $"      pagination: {{ modes: [{string.Join(", ", modes)}], defaultPageSize: {pagination.DefaultPageSize}, maxPageSize: {pagination.MaxPageSize} }},\n");
            body.Append("    },\n");
        }

        body.Append("  },\n} as const satisfies Model;\n\n");
    }

    private void WriteContext(StringBuilder body)
    {
        body.Append(CultureInfo.InvariantCulture, $"export interface {name}Context extends Context {{\n");
        foreach (var set in model.Sets.OrderBy(set => set.Name, StringComparer.Ordinal))
        {
            var writes = Writes(set).ToList();
            var arguments = writes.Count == 0 ? "" : $", {string.Join(" | ", writes.Select(Quote))}";
            body.Append(CultureInfo.InvariantCulture, $"  readonly {set.Name}: RestSet<{set.TypeName}, {ProxyName(set)}{arguments}>;\n");
        }

        body.Append("}\n\n");
        body.Append(CultureInfo.InvariantCulture, $"export function create{name}(options: ContextOptions): {name}Context {{\n");
        body.Append(CultureInfo.InvariantCulture, $"  return createContext({ModelName}, options) as unknown as {name}Context;\n");
        body.Append("}\n");
    }

    private string ModelName => JsonNamingPolicy.CamelCase.ConvertName(name) + "Model";

    private RestSetModel Target(RestNavigationModel navigation) => model.FindSet(navigation.Target)!;

    private static IEnumerable<string> Writes(RestSetModel set)
    {
        if (set.Allows(WriteOperations.Insert))
        {
            yield return "insert";
        }

        if (set.Allows(WriteOperations.Update))
        {
            yield return "update";
        }

        if (set.Allows(WriteOperations.Delete))
        {
            yield return "delete";
        }
    }

    private static string ProxyName(RestSetModel set) =>
        (set.TypeName.EndsWith("Dto", StringComparison.Ordinal) ? set.TypeName[..^3] : set.TypeName) + "Proxy";

    private static string ValueType(string type) => Kind(type) switch
    {
        "boolean" => "boolean",
        "number" => "number",
        "enum" => type,
        _ => "string",
    };

    private string ExpressionType(string type, bool nullable)
    {
        string Generic(string expression, string value)
        {
            _imports.Add(expression);
            return nullable ? $"{expression}<{value} | null>" : expression;
        }

        string Typed(string expression, string value)
        {
            _imports.Add(expression);
            return $"{expression}<{value}{(nullable ? " | null" : "")}>";
        }

        return Kind(type) switch
        {
            "number" => Generic("NumberExpr", "number"),
            "string" => Generic("StringExpr", "string"),
            "boolean" => nullable ? Typed("Expr", "boolean") : Generic("BoolExpr", "boolean"),
            "enum" => Typed("OrderedExpr", type),
            "datetime" or "datetimeoffset" => Generic("DateTimeExpr", "string"),
            "dateonly" => Generic("DateOnlyExpr", "string"),
            "timeonly" => Generic("TimeOnlyExpr", "string"),
            "timespan" => Typed("OrderedExpr", "string"),
            _ => Typed("Expr", "string"),
        };
    }

    /// <summary>The TypeScript client's member kind of a model type.</summary>
    private static string Kind(string type) => type switch
    {
        "bool" => "boolean",
        "uint8" or "int16" or "int32" or "int64" or "float32" or "float64" or "decimal" => "number",
        "string" => "string",
        "guid" => "guid",
        "dateTime" => "datetime",
        "dateTimeOffset" => "datetimeoffset",
        "dateOnly" => "dateonly",
        "timeOnly" => "timeonly",
        "timeSpan" => "timespan",
        "bytes" => "binary",
        _ => "enum",
    };

    // The built-in rules the client checks before saving; bounds are wire values (numbers or date/time strings).
    private static string Rules(RestPropertyRules? rules)
    {
        if (rules is null || rules.IsEmpty)
        {
            return "";
        }

        var parts = new List<string>();
        if (rules.IsRequired)
        {
            parts.Add("required: true");
        }

        if (rules.MinLength is { } minLength)
        {
            parts.Add($"minLength: {minLength.ToString(CultureInfo.InvariantCulture)}");
        }

        if (rules.MaxLength is { } maxLength)
        {
            parts.Add($"maxLength: {maxLength.ToString(CultureInfo.InvariantCulture)}");
        }

        if (rules.Min is { } min)
        {
            parts.Add($"min: {JsonValues.ToElement(min).GetRawText()}");
        }

        if (rules.Max is { } max)
        {
            parts.Add($"max: {JsonValues.ToElement(max).GetRawText()}");
        }

        if (rules.Pattern is { } pattern)
        {
            parts.Add($"pattern: {Quote(pattern)}");
        }

        return $", rules: {{ {string.Join(", ", parts)} }}";
    }

    private static string Bool(bool value) => value ? "true" : "false";

    private static string Quote(string value) => JsonSerializer.Serialize(value);
}
