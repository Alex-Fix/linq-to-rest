using System.Text.Json;
using System.Text.Json.Serialization;

namespace LinqToRest.Protocol;

/// <summary>The kind of a batch operation.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<BatchOperationKind>))]
public enum BatchOperationKind
{
    /// <summary>Insert a new row.</summary>
    [JsonStringEnumMemberName("insert")]
    Insert,

    /// <summary>Update the given members of a row.</summary>
    [JsonStringEnumMemberName("update")]
    Update,

    /// <summary>Delete a row.</summary>
    [JsonStringEnumMemberName("delete")]
    Delete,
}

/// <summary>A change set sent with <c>POST /$batch</c> and applied atomically.</summary>
public sealed class BatchRequest
{
    /// <summary>Gets the protocol version.</summary>
    [JsonPropertyName("v")]
    public required int Version { get; init; }

    /// <summary>Gets the operations, applied in order.</summary>
    public required IReadOnlyList<BatchOperation> Operations { get; init; }
}

/// <summary>One insert, update or delete of a batch.</summary>
public sealed class BatchOperation
{
    /// <summary>Gets the operation id, unique within the batch and echoed in results and errors.</summary>
    public required string Id { get; init; }

    /// <summary>Gets the operation kind.</summary>
    public required BatchOperationKind Op { get; init; }

    /// <summary>Gets the set name.</summary>
    public required string Set { get; init; }

    /// <summary>Gets the key values by wire name (update and delete).</summary>
    public IReadOnlyDictionary<string, JsonElement>? Key { get; init; }

    /// <summary>Gets the written member values by wire name (insert and update).</summary>
    public IReadOnlyDictionary<string, JsonElement>? Values { get; init; }

    /// <summary>Gets foreign key members whose value is the key generated by an earlier insert, by operation id.</summary>
    public IReadOnlyDictionary<string, string>? Refs { get; init; }

    /// <summary>Gets the concurrency token read with the row (update and delete).</summary>
    public JsonElement? Token { get; init; }
}

/// <summary>The response to a successful batch.</summary>
public sealed class BatchResponse
{
    /// <summary>Gets one result per operation, in request order.</summary>
    public required IReadOnlyList<BatchResult> Results { get; init; }
}

/// <summary>The result of one batch operation.</summary>
public sealed class BatchResult
{
    /// <summary>Gets the operation id.</summary>
    public required string Id { get; init; }

    /// <summary>Gets the row as re-read through the default projection (insert and update).</summary>
    public JsonElement? Value { get; init; }
}

/// <summary>One broken rule in the <c>errors</c> member of a <c>validation_failed</c> problem.</summary>
public sealed class ValidationIssue
{
    /// <summary>Gets the operation id; <see langword="null"/> only for <see cref="ErrorCodes.TooManyErrors"/>.</summary>
    public string? Operation { get; init; }

    /// <summary>Gets the JSON pointer of the value (<c>/operations/N/values/member</c>) or of the operation.</summary>
    [JsonPropertyName("pointer")]
    public string? Location { get; init; }

    /// <summary>Gets the member's wire name, or <see langword="null"/> when the error is about the whole row.</summary>
    public string? Member { get; init; }

    /// <summary>Gets the error code: a built-in one such as <see cref="ErrorCodes.Required"/>, or a custom one.</summary>
    public required string Code { get; init; }
}

[JsonSourceGenerationOptions(
    JsonSerializerDefaults.Web,
    UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
    AllowDuplicateProperties = false,
    RespectRequiredConstructorParameters = true,
    RespectNullableAnnotations = true,
    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
    MaxDepth = 32)]
[JsonSerializable(typeof(BatchRequest))]
[JsonSerializable(typeof(BatchResponse))]
[JsonSerializable(typeof(List<ValidationIssue>))]
internal sealed partial class BatchJsonContext : JsonSerializerContext;
