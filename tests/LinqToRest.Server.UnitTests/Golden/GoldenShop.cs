using LinqToRest.Modeling;
using LinqToRest.Server.Sets;
using Microsoft.EntityFrameworkCore;

namespace LinqToRest.Server.UnitTests.Golden;

// The sets behind tests/golden/model.json, which the client tests, the generators and the TypeScript client use.

public enum ProductStatus
{
    Draft,
    Active,
}

public sealed class Product
{
    public int Id { get; set; }
    public string Name { get; set; } = "";
    public string? Description { get; set; }
    public decimal Price { get; set; }
    public ProductStatus Status { get; set; }
    public Guid Version { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateOnly? ReleasedOn { get; set; }
    public Dimensions? Size { get; set; }
    public int TenantId { get; set; }
    public int? CategoryId { get; set; }
    public Category? Category { get; set; }
    public Guid? BinZone { get; set; }
    public Guid? BinSlot { get; set; }
    public Bin? Bin { get; set; }
    public List<OrderLine> Lines { get; set; } = [];
    public List<Tag> Tags { get; set; } = [];
    public List<Label> Labels { get; set; } = [];
}

public sealed class Category
{
    public int Id { get; set; }
    public string Name { get; set; } = "";
    public List<Product> Products { get; set; } = [];
}

/// <summary>Joined to products over a pure join table (many-to-many).</summary>
public sealed class Label
{
    public int Id { get; set; }
    public string Name { get; set; } = "";
}

/// <summary>A composite key, generated by EF Core.</summary>
public sealed class Bin
{
    public Guid Zone { get; set; }
    public Guid Slot { get; set; }
    public string Code { get; set; } = "";
}

public sealed class OrderLine
{
    public int Id { get; set; }
    public int ProductId { get; set; }
    public string Sku { get; set; } = "";
    public int Quantity { get; set; }
    public decimal UnitPrice { get; set; }
}

public sealed class Tag
{
    public int Id { get; set; }
    public int ProductId { get; set; }
    public string Value { get; set; } = "";
}

public sealed record Dimensions
{
    public required double Width { get; init; }
    public required Weight Weight { get; init; }
}

public sealed record Weight(decimal Amount, string Unit);

public sealed class GoldenContext(DbContextOptions<GoldenContext> options) : DbContext(options)
{
    public DbSet<Product> Products => Set<Product>();
    public DbSet<Category> Categories => Set<Category>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Product>().Property(p => p.Version).IsConcurrencyToken();
        modelBuilder.Entity<Product>().ComplexProperty(p => p.Size, size => size.ComplexProperty(d => d.Weight));
        modelBuilder.Entity<Product>().HasMany(p => p.Labels).WithMany().UsingEntity("ProductLabel");
        modelBuilder.Entity<Product>().HasOne(p => p.Bin).WithMany().HasForeignKey(p => new { p.BinZone, p.BinSlot });
        modelBuilder.Entity<Bin>(bin =>
        {
            bin.HasKey(b => new { b.Zone, b.Slot });
            bin.Property(b => b.Zone).ValueGeneratedOnAdd();
            bin.Property(b => b.Slot).ValueGeneratedOnAdd();
        });
    }
}

public sealed class GoldenProductSet : IEntitySetConfiguration<Product>
{
    public void Configure(EntitySetBuilder<Product> builder)
    {
        builder.ToSet("products").HasTypeName("ProductDto").AllowWrites(WriteOperations.All);
        builder.Property(p => p.Name).HasMaxLength(100);
        builder.Property(p => p.Description);
        builder.Property(p => p.Price).IsSortable().HasMin(0m).IsAggregatable();
        builder.Property(p => p.Status).IsGroupable();
        builder.HasConcurrencyToken(p => p.Version);
        builder.Property(p => p.CreatedAt).IsReadOnly();
        builder.Property(p => p.ReleasedOn);
        builder.Property(p => p.CategoryId).IsGroupable();
        builder.Value(p => p.Size);
        builder.Computed("tags", p => p.Tags.OrderBy(t => t.Value).Select(t => t.Value).ToList());
        builder.Computed("categoryName", p => p.Category != null ? p.Category.Name : null);
        builder.HasOne(p => p.Category).WithForeignKey(p => p.CategoryId);
        builder.Property(p => p.BinZone);
        builder.Property(p => p.BinSlot);
        builder.HasOne(p => p.Bin).WithForeignKey(p => new { p.BinZone, p.BinSlot });
        builder.HasMany(p => p.Lines).AllowLinks();
        builder.HasMany(p => p.Labels).AllowLinks();
    }
}

public sealed class GoldenCategorySet : IEntitySetConfiguration<Category>
{
    public void Configure(EntitySetBuilder<Category> builder)
    {
        builder.ToSet("categories").HasTypeName("CategoryDto").AllowWrites(WriteOperations.All);
        builder.Property(c => c.Name).IsGroupable();
        builder.HasMany(c => c.Products).AllowLinks();
        builder.HasPagination(p => p.Modes(PaginationModes.Cursor).DefaultPageSize(2));
    }
}

public sealed class GoldenLabelSet : IEntitySetConfiguration<Label>
{
    public void Configure(EntitySetBuilder<Label> builder)
    {
        builder.ToSet("labels").HasTypeName("LabelDto").AllowWrites(WriteOperations.Insert);
        builder.Property(l => l.Name);
    }
}

public sealed class GoldenBinSet : IEntitySetConfiguration<Bin>
{
    public void Configure(EntitySetBuilder<Bin> builder)
    {
        builder.ToSet("bins").HasTypeName("BinDto").AllowWrites(WriteOperations.Insert);
        builder.Property(b => b.Code);
    }
}

public sealed class GoldenOrderLineSet : IEntitySetConfiguration<OrderLine>
{
    public void Configure(EntitySetBuilder<OrderLine> builder)
    {
        builder.ToSet("orderLines").HasTypeName("OrderLineDto").AllowWrites(WriteOperations.All);
        builder.Property(l => l.Sku);
        builder.Property(l => l.Quantity).IsAggregatable();
        builder.Property(l => l.UnitPrice).IsAggregatable();
        builder.HasPagination(p => p.Modes(PaginationModes.Offset));
    }
}

public sealed class GoldenDimensionsType : IValueTypeConfiguration<Dimensions>
{
    public void Configure(ValueTypeBuilder<Dimensions> builder)
    {
        builder.HasTypeName("DimensionsDto");
        builder.Property(d => d.Width).IsSortable().HasMin(0d);
        builder.Value(d => d.Weight);
    }
}

public sealed class GoldenWeightType : IValueTypeConfiguration<Weight>
{
    public void Configure(ValueTypeBuilder<Weight> builder)
    {
        builder.HasTypeName("WeightDto");
        builder.Property(w => w.Amount).IsAggregatable();
        builder.Property(w => w.Unit).HasMaxLength(5);
    }
}
