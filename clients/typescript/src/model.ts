/** The scalar kinds of DTO members, as generated from the .NET model. */
export type MemberKind =
  | "boolean"
  | "number"
  | "string"
  | "enum"
  | "guid"
  | "datetime"
  | "datetimeoffset"
  | "dateonly"
  | "timeonly"
  | "timespan"
  | "binary";

/** A scalar or primitive-collection member of a DTO. */
export interface MemberModel {
  readonly name: string;
  readonly kind: MemberKind;
  readonly nullable: boolean;
  readonly collection: boolean;
  readonly filterable: boolean;
  readonly sortable: boolean;
  readonly writable: boolean;
}

/** A navigation to another set. */
export interface NavigationModel {
  readonly name: string;
  readonly target: string;
  readonly collection: boolean;
  readonly foreignKey: string | null;
}

export type PaginationMode = "offset" | "cursor";

/** One set of the API and its DTO. */
export interface SetModel {
  readonly name: string;
  readonly key: readonly string[];
  readonly token: string | null;
  readonly members: readonly MemberModel[];
  readonly navigations: readonly NavigationModel[];
  readonly pagination: {
    readonly modes: readonly PaginationMode[];
    readonly defaultPageSize: number;
    readonly maxPageSize: number;
  };
}

/** The DTO model generated by `linqtorest-ts` from the .NET contracts. */
export interface Model {
  readonly sets: Readonly<Record<string, SetModel>>;
}

export function findSet(model: Model, name: string): SetModel {
  const set = model.sets[name];
  if (set === undefined) {
    throw new Error(`The model has no set "${name}".`);
  }

  return set;
}
