/** The scalar kinds of members, as generated from the model document. */
export type MemberKind =
  | "boolean"
  | "number"
  | "string"
  | "enum"
  | "guid"
  | "datetime"
  | "datetimeoffset"
  | "dateonly"
  | "timeonly"
  | "timespan"
  | "binary";

/**
 * The built-in validation rules of a writable member, from the model document. The client checks them before saving;
 * the server checks them again, with any rules of its own.
 */
export interface MemberRules {
  /** Not null or missing, and for strings and collections not empty or blank. */
  readonly required?: boolean;
  /** Minimum string length or item count. */
  readonly minLength?: number;
  /** Maximum string length or item count. */
  readonly maxLength?: number;
  /** Inclusive lower bound: a number, or a date/time string in the member's wire format. */
  readonly min?: number | string;
  /** Inclusive upper bound: a number, or a date/time string in the member's wire format. */
  readonly max?: number | string;
  /** The pattern a string must match (JavaScript syntax, no flags). */
  readonly pattern?: string;
}

/** A scalar or primitive-collection member of a set. */
export interface MemberModel {
  readonly name: string;
  readonly kind: MemberKind;
  readonly nullable: boolean;
  readonly collection: boolean;
  readonly filterable: boolean;
  readonly sortable: boolean;
  readonly writable: boolean;
  /** Whether grouped queries may use the member as a key (`IsGroupable()`). */
  readonly groupable?: boolean;
  /** Whether sum, min, max and average over groups may read the member (`IsAggregatable()`). */
  readonly aggregatable?: boolean;
  readonly rules?: MemberRules;
}

/** A navigation to another set. */
export interface NavigationModel {
  readonly name: string;
  readonly target: string;
  readonly collection: boolean;
  readonly foreignKey: string | null;
}

export type PaginationMode = "offset" | "cursor";

/** A write a set may allow through `saveChanges`. Sets are read-only unless they allow some. */
export type WriteOperation = "insert" | "update" | "delete";

/** One set of the API. */
export interface SetModel {
  readonly name: string;
  readonly key: readonly string[];
  readonly token: string | null;
  readonly writes: readonly WriteOperation[];
  readonly members: readonly MemberModel[];
  readonly navigations: readonly NavigationModel[];
  readonly pagination: {
    readonly modes: readonly PaginationMode[];
    readonly defaultPageSize: number;
    readonly maxPageSize: number;
  };
}

/** The model generated by `linqtorest-gen ts` from the server's model document. */
export interface Model {
  readonly sets: Readonly<Record<string, SetModel>>;
}

/** Fails before anything is sent when the set doesn't allow the write (the server would refuse it). */
export function requireWrite(set: SetModel, operation: WriteOperation, description: string): void {
  if (!set.writes.includes(operation)) {
    throw new Error(`The set '${set.name}' doesn't allow ${description}.`);
  }
}

export function findSet(model: Model, name: string): SetModel {
  const set = model.sets[name];
  if (set === undefined) {
    throw new Error(`The model has no set "${name}".`);
  }

  return set;
}
